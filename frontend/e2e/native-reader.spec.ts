test('installed reference details reuse View without executing or writing in the installed library',async({page})=>{
 const name='reader-installed-'+Date.now()+'.mq.md',kb=path.join(project,'kb'),file=path.join(kb,name);
 fs.mkdirSync(kb,{recursive:true});const cached=fs.existsSync(path.join(kb,'.agent'));
 fs.writeFileSync(file,'---\nmarkup: occlusion\ntitle: 安装参考文稿\n---\n\n## explain\n\n这是参考资料，不是假装已经验证的可执行知识。我们[解释一段表达式](2+3)，但不会在阅读时执行它。\n\nReturn *2+3*.\n');
 try{
  await page.goto('/app?section=knowledge');
  const card=page.locator('.library-card').filter({hasText:name.slice(0,-3)});await expect(card).toContainText('参考文稿');
  const popupPromise=page.waitForEvent('popup');await card.getByRole('link',{name:'查看详情'}).click();const popup=await popupPromise;
  await expect(popup.frameLocator('iframe.native-view').locator('body')).toContainText('这是参考资料');
  await expect(popup.getByRole('button',{name:'运行与验证',exact:true})).toHaveCount(0);
  expect(fs.existsSync(path.join(kb,'.agent'))).toBe(cached);await popup.close();
 }finally{fs.rmSync(file,{force:true})}
});
